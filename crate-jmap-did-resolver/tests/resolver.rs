/// An in-process `Fetch`: serves canned bodies, statuses or
/// [`FetchError::TooLarge`] by URL (404 for anything else) and records
/// every URL requested.
#[derive(Default)]
struct Stub {
    responses: Mutex<HashMap<String, Result<Vec<u8>, u16>>>,
    too_large: Mutex<Vec<String>>,
    calls: Mutex<Vec<String>>,
}

impl Stub {
    fn serve(&self, url: &str, body: &Value) {
        let body = serde_json::to_vec(body).unwrap();
        self.responses
            .lock()
            .unwrap()
            .insert(url.to_owned(), Ok(body));
    }

    fn serve_bytes(&self, url: &str, body: &[u8]) {
        self.responses
            .lock()
            .unwrap()
            .insert(url.to_owned(), Ok(body.to_vec()));
    }

    fn fail(&self, url: &str, status: u16) {
        self.responses
            .lock()
            .unwrap()
            .insert(url.to_owned(), Err(status));
    }

    fn too_large(&self, url: &str) {
        self.too_large.lock().unwrap().push(url.to_owned());
    }

    fn calls(&self) -> Vec<String> {
        self.calls.lock().unwrap().clone()
    }
}

impl Fetch for &Stub {
    async fn get(&self, url: &str) -> Result<Vec<u8>, FetchError> {
        self.calls.lock().unwrap().push(url.to_owned());
        if self.too_large.lock().unwrap().iter().any(|u| u == url) {
            return Err(FetchError::TooLarge);
        }
        match self.responses.lock().unwrap().get(url) {
            Some(Ok(body)) => Ok(body.clone()),
            Some(Err(status)) => Err(FetchError::Status(*status)),
            None => Err(FetchError::Status(404)),
        }
    }
}

/// A clock that stands still until the test advances it.
fn clock() -> (Arc<AtomicU64>, impl Fn() -> Instant + Send + Sync + 'static) {
    let start = Instant::now();
    let elapsed = Arc::new(AtomicU64::new(0));
    let reader = Arc::clone(&elapsed);
    (elapsed, move || {
        start + Duration::from_secs(reader.load(Ordering::SeqCst))
    })
}

fn did(s: &str) -> Did {
    s.parse().unwrap()
}

fn fixture(name: &str) -> Value {
    let path = format!("{}/tests/fixtures/plc/{name}", env!("CARGO_MANIFEST_DIR"));
    serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap()
}

/// A hand-written did:web document for `ALICE`, with key `key`.
fn alice_document(key: &str) -> Value {
    json!({
        "@context": ["https://www.w3.org/ns/did/v1"],
        "id": ALICE,
        "verificationMethod": [{
            "id": format!("{ALICE}#{key}"),
            "type": "Multikey",
            "controller": ALICE,
            "publicKeyMultibase": "z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK"
        }]
    })
}

fn document(resolved: Resolved) -> Value {
    match resolved {
        Resolved::Document(document) => document,
        other => panic!("expected a DID document, got {other:?}"),
    }
}

