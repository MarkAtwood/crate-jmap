const TTL: Duration = Duration::from_secs(300);

const ALICE: &str = "did:web:w3c-ccg.github.io:user:alice";
/// did:web §Read (Resolve) example: "did:web:w3c-ccg.github.io:user:alice
/// -> https://w3c-ccg.github.io/user/alice/did.json".
const ALICE_URL: &str = "https://w3c-ccg.github.io/user/alice/did.json";

const EWVI: &str = "did:plc:ewvi7nxzyoun6zhxrhs64oiz";
/// did:plc §DID Resolution: "The audit history of a given DID ... can be
/// found at: `https://plc.directory/:did/log/audit`".
const EWVI_URL: &str = "https://plc.directory/did:plc:ewvi7nxzyoun6zhxrhs64oiz/log/audit";

/// An in-process `Fetch`: serves canned bodies or statuses by URL (404
/// for anything else) and records every URL requested.
#[derive(Default)]
struct Stub {
    responses: Mutex<HashMap<String, Result<Vec<u8>, u16>>>,
    calls: Mutex<Vec<String>>,
}

impl Stub {
    fn serve(&self, url: &str, body: &Value) {
        let body = serde_json::to_vec(body).unwrap();
        self.responses
            .lock()
            .unwrap()
            .insert(url.to_owned(), Ok(body));
    }

    fn fail(&self, url: &str, status: u16) {
        self.responses
            .lock()
            .unwrap()
            .insert(url.to_owned(), Err(status));
    }

    fn calls(&self) -> Vec<String> {
        self.calls.lock().unwrap().clone()
    }
}

impl Fetch for &Stub {
    async fn get(&self, url: &str) -> Result<Vec<u8>, FetchError> {
        self.calls.lock().unwrap().push(url.to_owned());
        match self.responses.lock().unwrap().get(url) {
            Some(Ok(body)) => Ok(body.clone()),
            Some(Err(status)) => Err(FetchError::Status(*status)),
            None => Err(FetchError::Status(404)),
        }
    }
}

/// A clock that stands still until the test advances it.
fn clock() -> (Arc<AtomicU64>, impl Fn() -> Instant + Send + Sync + 'static) {
    let start = Instant::now();
    let elapsed = Arc::new(AtomicU64::new(0));
    let reader = Arc::clone(&elapsed);
    (elapsed, move || {
        start + Duration::from_secs(reader.load(Ordering::SeqCst))
    })
}

fn did(s: &str) -> Did {
    s.parse().unwrap()
}

fn fixture(name: &str) -> Value {
    let path = format!("{}/tests/fixtures/plc/{name}", env!("CARGO_MANIFEST_DIR"));
    serde_json::from_slice(&std::fs::read(path).unwrap()).unwrap()
}

/// A hand-written did:web document for `ALICE`, with key `key`.
fn alice_document(key: &str) -> Value {
    json!({
        "@context": ["https://www.w3.org/ns/did/v1"],
        "id": ALICE,
        "verificationMethod": [{
            "id": format!("{ALICE}#{key}"),
            "type": "Multikey",
            "controller": ALICE,
            "publicKeyMultibase": "z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK"
        }]
    })
}

fn document(resolved: Resolved) -> Value {
    match resolved {
        Resolved::Document(document) => document,
        other => panic!("expected a DID document, got {other:?}"),
    }
}

// ---------------------------------------------------------------- did:key

#[tokio::test]
async fn did_key_is_derived_without_a_fetch() {
    // did:key v0.9: the document is generated from the DID ("expand a
    // DID into a DID Document"); its Multikey publicKeyMultibase is the
    // DID's multibase value. jmap-chat-did-guide: "did:key requires no
    // caching." The DID is the draft-atwood-jmap-did-00 example.
    let stub = Stub::default();
    let resolver = Resolver::new(&stub, TTL);
    let d = "did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK";
    let doc = document(resolver.resolve(&did(d)).await.unwrap());
    assert_eq!(doc["id"], d);
    assert_eq!(
        doc["verificationMethod"][0]["publicKeyMultibase"],
        "z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK"
    );
    assert!(resolver.refresh(&did(d)).await.is_ok());
    assert!(stub.calls().is_empty());
}

