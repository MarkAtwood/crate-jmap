/// DIF did:webvh v1.0 §The DID to HTTPS Transformation example:
/// "`did:webvh:{SCID}:example.com` --> `https://example.com/.well-known/did.jsonl`".
const WEBVH_LOG_URL: &str = "https://example.com/.well-known/did.jsonl";
/// "The URL for the extra file is defined by replacing the `/did.jsonl` at
/// the end of the DID Log URL with `/did-witness.json`."
const WEBVH_WITNESS_URL: &str = "https://example.com/.well-known/did-witness.json";

fn webvh_fixture(scenario: &str, file: &str) -> Vec<u8> {
    let path = format!(
        "{}/tests/fixtures/webvh/{scenario}/{file}",
        env!("CARGO_MANIFEST_DIR")
    );
    std::fs::read(path).unwrap()
}

/// The DID and latest `versionId` of the scenario's own resolution result.
fn webvh_expected(scenario: &str) -> (Did, String) {
    let result: Value =
        serde_json::from_slice(&webvh_fixture(scenario, "resolutionResult.json")).unwrap();
    (
        did(result["didDocument"]["id"].as_str().unwrap()),
        result["didDocumentMetadata"]["versionId"]
            .as_str()
            .unwrap()
            .to_owned(),
    )
}

/// The `versionId` of the log's first entry, as written by the generator.
fn first_version_id(log: &[u8]) -> String {
    let first = log.split(|&b| b == b'\n').next().unwrap();
    let entry: Value = serde_json::from_slice(first).unwrap();
    entry["versionId"].as_str().unwrap().to_owned()
}

fn webvh_log(resolved: Resolved) -> WebvhLog {
    match resolved {
        Resolved::Webvh(log) => log,
        other => panic!("expected a did:webvh log, got {other:?}"),
    }
}

