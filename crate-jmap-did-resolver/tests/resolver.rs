//! Tests for `Resolver` and `HttpFetcher`, all offline: the resolver
//! fetches through an in-process stub, and `HttpFetcher` talks to a
//! local wiremock server.
//!
//! Oracles, none produced by this crate:
//!
//! - draft-atwood-jmap-chat-did-00 (jmap-chat-spec 6bcd9d8) §Caching L233
//!   and §Resolution failure handling L237, quoted at each test.
//! - did:web Method Specification (<https://w3c-ccg.github.io/did-method-web/>)
//!   §Read (Resolve) and its `w3c-ccg.github.io/user/alice` example.
//! - did:key Method v0.9 (<https://w3c-ccg.github.io/did-key-spec/>) and
//!   the draft-atwood-jmap-did-00 example DID.
//! - did:plc Method Specification v0.3.0
//!   (<https://web.plc.directory/spec/v0.1/did-plc>) §DID Resolution and
//!   §Identifier Syntax. `tests/fixtures/plc/ewvi7nxzyoun6zhxrhs64oiz.*`
//!   are the audit log and `/data` state fetched from plc.directory on
//!   2026-10-20; `synthetic.json` was generated by the did:plc reference
//!   implementation (`synthetic.js`). Both are copied from
//!   jmap-did-types.

