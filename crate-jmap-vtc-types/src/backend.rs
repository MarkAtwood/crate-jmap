//! [`jmap_types::JmapObject`] impls for the VTC data types.
//!
//! Defined here so that `jmap-vtc-server` can use them without violating
//! the orphan rule. The type names are those of draft-atwood-jmap-vtc-00
//! §JMAP Data Type Registration.

use jmap_types::{GetObject, JmapObject, PatchObject, QueryObject, SetObject};

use crate::query::{
    VtcCallComparator, VtcCallFilter, VtcLivestreamFilter, VtcMediaComparator,
    VtcParticipantComparator, VtcParticipantFilter, VtcRecordingFilter,
};
use crate::{VtcCall, VtcLivestream, VtcParticipant, VtcRecording};

impl JmapObject for VtcCall {
    const TYPE_NAME: &'static str = "VTCCall";
    type Property = ();
}

impl GetObject for VtcCall {}

/// draft-atwood-jmap-vtc-00 §VTCCall Object Fields (lines 393-474): `id`,
/// `createdAt` and `initiatorId` are "immutable, server-set"; `accountId`,
/// `endedAt`, `endReason`, `activeParticipantCount` and `breakoutRoomIds`
/// are "server-set"; `callType` and `parentCallId` are "immutable".
///
/// §VTCCall/set: "The server sets `id`, `initiatorId`, `createdAt`,
/// `state`, and `joinUri`", and `joinUri` is "Generated by the server" with
/// no update changing it, so it is server-set here. `state` stays
/// client-settable: a moderator may set it to `"ended"`.
impl SetObject for VtcCall {
    type Patch = PatchObject;
    const SERVER_SET: &'static [&'static str] = &[
        "id",
        "accountId",
        "createdAt",
        "endedAt",
        "endReason",
        "initiatorId",
        "joinUri",
        "activeParticipantCount",
        "breakoutRoomIds",
    ];
    const CLIENT_SETTABLE: &'static [&'static str] = &[
        "callType",
        "state",
        "subject",
        "joinPassword",
        "mediaTypes",
        "lobbyEnabled",
        "policy",
        "parentCallId",
        "scheduledStartAt",
        "gatewayPin",
        "e2eeEnabled",
        "chatId",
        "spaceId",
        "channelId",
        "calendarEventId",
    ];
    const IMMUTABLE: &'static [&'static str] = &["callType", "parentCallId"];
}

impl QueryObject for VtcCall {
    type Filter = VtcCallFilter;
    type Comparator = VtcCallComparator;
}

impl JmapObject for VtcParticipant {
    const TYPE_NAME: &'static str = "VTCParticipant";
    type Property = ();
}

impl GetObject for VtcParticipant {}

/// draft-atwood-jmap-vtc-00 §VTCParticipant Object Fields (lines 329-380):
/// `id` and `userId` are "immutable, server-set"; `joinedAt` and
/// `speakerTimeMs` are "server-set"; `callId` is "immutable".
///
/// `e2eeFingerprint` is the key fingerprint "as reported by the media
/// layer", never sent by a client, so it is server-set here. A dial-out
/// create may carry `gatewayData`, which the server then "stores and relays
/// ... without interpretation"; an update reaches it only through
/// §VTCGatewaySignal, so it is immutable here.
impl SetObject for VtcParticipant {
    type Patch = PatchObject;
    const SERVER_SET: &'static [&'static str] = &[
        "id",
        "userId",
        "joinedAt",
        "speakerTimeMs",
        "e2eeFingerprint",
    ];
    const CLIENT_SETTABLE: &'static [&'static str] = &[
        "callId",
        "displayName",
        "role",
        "leftAt",
        "callResponse",
        "joinMethod",
        "gatewayData",
        "lobbyState",
        "mediaState",
        "kickedBy",
        "unmuteRequested",
        "breakoutCallId",
    ];
    const IMMUTABLE: &'static [&'static str] = &["callId", "gatewayData"];
}

impl QueryObject for VtcParticipant {
    type Filter = VtcParticipantFilter;
    type Comparator = VtcParticipantComparator;
}

