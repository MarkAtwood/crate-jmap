//! Tests for the pure did:webvh log verifier.
//!
//! Oracles, none produced by this crate:
//!
//! - `tests/fixtures/webvh/` is the `vectors/` directory of the DIF
//!   did:webvh test suite (<https://github.com/decentralized-identity/didwebvh-test-suite>,
//!   commit 703f97f, Apache-2.0), limited to each implementation's
//!   `did.jsonl`, `did-witness.json` and `resolutionResult*.json`. The
//!   positive scenarios were generated and resolved by five independent
//!   implementations (dart, java, java-eecc, python, rust) and the
//!   didwebvh-ts reference implementation; the expected versions,
//!   documents and metadata are those implementations' own resolution
//!   results. The `negative-*` scenarios were generated by didwebvh-ts,
//!   and their expected outcomes quote the scenario's `README.md` and the
//!   DIF did:webvh v1.0 specification
//!   (<https://identity.foundation/didwebvh/v1.0/>).
//! - DID syntax cases not in the suite quote the v1.0 Method-Specific
//!   Identifier and DID-to-HTTPS Transformation sections.

use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime, UNIX_EPOCH};

use jmap_did_types::{verify_webvh_log, Did, WebvhError, WebvhLog};
use serde_json::Value;

/// 2026-10-20T00:00:00Z, after every fixture's `versionTime`.
const NOW_SECS: u64 = 1_792_454_400;

/// A SCID from the suite, used where a test needs a well-formed one.
const SCID: &str = "QmV2V5CSzH5w9UF4rHHAdktXL93ounugmgV2LXVCx9s2i9";

fn now() -> SystemTime {
    UNIX_EPOCH + Duration::from_secs(NOW_SECS)
}

fn fixtures() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/webvh")
}

fn read(path: &Path) -> Vec<u8> {
    fs::read(path).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn json(path: &Path) -> Value {
    serde_json::from_slice(&read(path)).unwrap()
}

fn did(s: &str) -> Did {
    s.parse().unwrap()
}

/// The `state.id` of the log's first entry: the DID the scenario created.
fn created_did(log: &[u8]) -> Did {
    let first = log.split(|&b| b == b'\n').next().unwrap();
    let entry: Value = serde_json::from_slice(first).unwrap();
    did(entry["state"]["id"].as_str().unwrap())
}

/// Verifies `scenario/impl` against the DID its first entry created.
fn verify(scenario: &str, implementation: &str) -> Result<WebvhLog, WebvhError> {
    let dir = fixtures().join(scenario).join(implementation);
    let log = read(&dir.join("did.jsonl"));
    let witness = dir
        .join("did-witness.json")
        .exists()
        .then(|| read(&dir.join("did-witness.json")));
    verify_webvh_log(&created_did(&log), &log, witness.as_deref(), now())
}

/// Asserts that `ours` is the resolved `expected` document less the
/// implicit `#files` and `#whois` services resolvers add (v1.0 §DID URL
/// Resolution: "The `did:webvh` method implicitly defines this
/// service").
fn assert_document(ours: &Value, expected: &Value, context: &str) {
    let (Value::Object(ours), Value::Object(expected)) = (ours, expected) else {
        panic!("{context}: documents are not objects");
    };
    for key in ours.keys().chain(expected.keys()) {
        if key != "service" {
            assert_eq!(ours.get(key), expected.get(key), "{context}: {key}");
        }
    }
    let services = expected
        .get("service")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    for service in ours
        .get("service")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        assert!(services.contains(service), "{context}: {service}");
    }
}

/// The happy-path scenarios of the suite, each resolved by at least four
/// implementations.
const SCENARIOS: [&str; 13] = [
    "basic-create",
    "basic-update",
    "deactivate",
    "key-rotation",
    "multi-update",
    "multiple-update-keys",
    "portable",
    "portable-move",
    "pre-rotation",
    "pre-rotation-consume",
    "services",
    "witness-threshold",
    "witness-update",
];

#[test]
fn every_implementations_logs_verify_to_its_own_resolution() {
    let mut checked = 0;
    for scenario in SCENARIOS {
        let mut implementations = 0;
        for entry in fs::read_dir(fixtures().join(scenario)).unwrap() {
            let dir = entry.unwrap().path();
            if !dir.join("did.jsonl").exists() {
                continue;
            }
            let implementation = dir.file_name().unwrap().to_str().unwrap().to_owned();
            let context = format!("{scenario}/{implementation}");
            let log =
                verify(scenario, &implementation).unwrap_or_else(|e| panic!("{context}: {e:?}"));
            assert_eq!(log.invalid_entry(), None, "{context}");
            implementations += 1;

            for result in fs::read_dir(&dir).unwrap() {
                let path = result.unwrap().path();
                let name = path.file_name().unwrap().to_str().unwrap().to_owned();
                let Some(selector) = name
                    .strip_prefix("resolutionResult")
                    .and_then(|s| s.strip_suffix(".json"))
                else {
                    continue;
                };
                let context = format!("{context}/{name}");
                let expected = json(&path);
                let meta = &expected["didDocumentMetadata"];
                // resolutionResult.<n>.json resolves `?versionNumber=<n>`,
                // except that didwebvh-py ignored the selector and resolved
                // the latest version, so the version is the one the result
                // names.
                let version_id = meta["versionId"].as_str().unwrap();
                let version = log
                    .version(version_id)
                    .unwrap_or_else(|| panic!("{context}: {version_id}"));
                if selector.is_empty() {
                    assert_eq!(log.latest(), version, "{context}");
                }
                if let Some(scid) = meta["scid"].as_str() {
                    assert_eq!(log.scid(), scid, "{context}");
                }
                if let Some(portable) = meta["portable"].as_bool() {
                    assert_eq!(version.parameters.portable, portable, "{context}");
                }
                if let Some(keys) = meta["updateKeys"].as_array() {
                    let keys: Vec<&str> = keys.iter().map(|k| k.as_str().unwrap()).collect();
                    assert_eq!(version.parameters.update_keys, keys, "{context}");
                }
                let deactivated = meta["deactivated"].as_bool().unwrap_or(false);
                if selector.is_empty() {
                    assert_eq!(log.is_deactivated(), deactivated, "{context}");
                    assert_eq!(log.current().is_some(), !deactivated, "{context}");
                }
                match &expected["didDocument"] {
                    // "a resolver MUST NOT return the DIDDoc" once deactivated.
                    Value::Null => assert!(deactivated, "{context}"),
                    document => assert_document(&version.document, document, &context),
                }
                checked += 1;
            }
        }
        assert!(
            implementations >= 4,
            "{scenario}: {implementations} implementations"
        );
    }
    assert!(checked >= 80, "{checked} resolution results");
}

#[test]
fn multi_update_versions_resolve_by_version_id() {
    let log = verify("multi-update", "ts").unwrap();
    let numbers: Vec<u64> = log.versions().map(|v| v.version_number).collect();
    assert_eq!(numbers, [1, 2, 3]);
    assert_eq!(log.latest().version_number, 3);
    assert_eq!(log.version("2-not-in-the-log"), None);
}

// ------------------------------------------------- negative vectors (suite)

/// Asserts that the log's first entry fails, so the whole log is rejected.
fn assert_rejected(scenario: &str, expected: WebvhError) {
    assert_eq!(verify(scenario, "ts").err(), Some(expected), "{scenario}");
}

/// Asserts that entry `index` fails: it and every later entry are
/// invalid, the earlier versions stay resolvable, and the DID itself does
/// not resolve ("marking all entries from the first invalid entry to the
/// end of the log as invalid").
fn assert_invalid_from(scenario: &str, index: usize, expected: WebvhError) {
    let log = verify(scenario, "ts").unwrap_or_else(|e| panic!("{scenario}: {e:?}"));
    assert_eq!(log.invalid_entry(), Some((index, &expected)), "{scenario}");
    assert_eq!(log.versions().count(), index, "{scenario}");
    assert_eq!(log.current(), None, "{scenario}");
    let earlier = log.latest().version_id.clone();
    assert_eq!(
        log.version(&earlier).map(|v| v.version_number),
        Some(index as u64)
    );
}

