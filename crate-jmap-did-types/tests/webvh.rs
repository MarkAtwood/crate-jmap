#[test]
fn altered_signature_is_rejected() {
    // "The Data Integrity proof in the entry MUST be valid". The proof is
    // outside the entry hash, so only the signature check sees this.
    let log = String::from_utf8(read(&fixtures().join("basic-create/ts/did.jsonl"))).unwrap();
    let did = created_did(log.as_bytes());
    let signature =
        "z2gbCNg9WYQHGgRA4zqk7nCUz68FRkASqt9ojSXdDJyYYHYQqCAEXujM2h6ugBSfkaGBKhq7H4LJJYHwaJ5jvtkTN";
    let altered = log.replace(signature, &signature.replace("z2gbC", "z2gbD"));
    assert_ne!(altered, log);
    assert_eq!(
        verify_webvh_log(&did, altered.as_bytes(), None, now()).err(),
        Some(WebvhError::InvalidProof)
    );
}
