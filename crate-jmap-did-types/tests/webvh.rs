// ---------------------------------------------------------- DID syntax

#[test]
fn suite_literal_dids_are_invalid() {
    // The suite's `resolve-did` cases, all `expectError: invalidDid`.
    // Their placeholder SCID has `0`, outside base58btc.
    let rejected = [
        "did:webvh:Qm0000000000000000000000000000000000000000000000:127.0.0.1%3a8080",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:example.com:..:..:admin",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:127%2E0%2E0%2E1",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:127%2e0%2e0%2e1",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:169%2E254%2E169%2E254",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:example.com:%2E%2E:admin",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:example.com:%2e%2e:admin",
        "did:webvh:Qm0000000000000000000000000000000000000000000000:example.com:a%2Fb",
    ];
    for s in rejected {
        assert_eq!(
            verify_webvh_log(&did(s), b"", None, now()).err(),
            Some(WebvhError::InvalidDid),
            "{s}"
        );
    }
    // A fragment is not part of the DID at all.
    assert!(
        Did::parse("did:webvh:Qm0000000000000000000000000000000000000000000000:127.0.0.1#x")
            .is_err()
    );
}

#[test]
fn domain_and_path_rules_apply_with_a_valid_scid() {
    let rejected = [
        // "the domain MUST NOT be an IPv4 or IPv6 address, including a
        // non-canonical textual representation that a URL parser would
        // normalize to an IP address"
        "127.0.0.1",
        "127%2E0%2E0%2E1",
        "127.0.0.1%3a8080",
        "0x7f.1",
        // "port-number MUST represent a decimal integer in the range 1
        // through 65535 inclusive"
        "example.com%3A0",
        "example.com%3A65536",
        "example.com%3A123456",
        // "The domain component MUST NOT contain more than one
        // percent-encoded port separator."
        "example.com%3A80%3A80",
        // "A percent-encoded colon MUST NOT appear within
        // encoded-domain-name"
        "exa%3Ample.com",
        // "encoded-domain-name = encoded-domain-label 1*( "." ... )"
        "localhost",
        "under_score.example.com",
        // "every DNS label MUST be non-empty, no more than 63 octets"
        "example%2E%2Ecom",
        &format!("{}.example.com", "a".repeat(64)),
        // Path segments: "MUST NOT be `.` or `..`", "MUST NOT contain
        // `/`, `\\`, or U+0000", "MUST NOT begin or end with whitespace"
        "example.com:..:admin",
        "example.com:%2E",
        "example.com:a%2Fb",
        "example.com:a%5Cb",
        "example.com:a%00b",
        "example.com:%20a",
        "example.com:a%20",
    ];
    for rest in rejected {
        let s = format!("did:webvh:{SCID}:{rest}");
        assert_eq!(
            verify_webvh_log(&did(&s), b"", None, now()).err(),
            Some(WebvhError::InvalidDid),
            "{s}"
        );
    }

    let accepted = [
        "example.com",
        "issuer.example.com",
        "example.com:dids:issuer",
        "example.com%3A3000:dids:issuer",
        // "`%3A` accepts either `%3A` or `%3a`"
        "example.com%3a3000",
        "example.com%3A65535",
        // The internationalized example `jp納豆.例.jp:用户`, percent-encoded
        // as DID Core requires.
        "jp%E7%B4%8D%E8%B1%86.%E4%BE%8B.jp:%E7%94%A8%E6%88%B7",
        &format!("{}.example.com", "a".repeat(63)),
    ];
    for rest in accepted {
        let s = format!("did:webvh:{SCID}:{rest}");
        assert_eq!(
            verify_webvh_log(&did(&s), b"", None, now()).err(),
            Some(WebvhError::EmptyLog),
            "{s}"
        );
    }

    // Not did:webvh, or a SCID that is not 46 base58btc characters.
    for s in [
        format!("did:web:{SCID}:example.com"),
        format!("did:webvh:{}:example.com", &SCID[1..]),
        format!("did:webvh:{SCID}"),
    ] {
        assert_eq!(
            verify_webvh_log(&did(&s), b"", None, now()).err(),
            Some(WebvhError::InvalidDid),
            "{s}"
        );
    }
}

// ---------------------------------------------------- tampering and time

fn basic_update_ts() -> (Did, Vec<u8>) {
    let log = read(&fixtures().join("basic-update/ts/did.jsonl"));
    (created_did(&log), log)
}

#[test]
fn altered_entry_breaks_the_hash_chain_from_there_on() {
    // "Verify that the calculated value matches the extracted `entryHash`
    // value [...]. If not, terminate the resolution process with an
    // error." Entry 2 lists `did:web:example.com` in `alsoKnownAs`.
    let (did, log) = basic_update_ts();
    let text = String::from_utf8(log).unwrap();
    let mut lines: Vec<&str> = text.lines().collect();
    let altered = lines[1].replace("did:web:example.com", "did:web:example.org");
    assert_ne!(altered, lines[1]);
    lines[1] = &altered;
    let log = verify_webvh_log(&did, lines.join("\n").as_bytes(), None, now()).unwrap();
    assert_eq!(
        log.invalid_entry(),
        Some((1, &WebvhError::EntryHashMismatch))
    );
    assert_eq!(log.latest().version_number, 1);
    assert_eq!(log.current(), None);
}

#[test]
fn reordered_entries_are_rejected() {
    // "The version number MUST be `1` for the first entry".
    let (did, log) = basic_update_ts();
    let text = String::from_utf8(log).unwrap();
    let lines: Vec<&str> = text.lines().collect();
    let swapped = format!("{}\n{}\n", lines[1], lines[0]);
    assert_eq!(
        verify_webvh_log(&did, swapped.as_bytes(), None, now()).err(),
        Some(WebvhError::InvalidVersionId)
    );
}

#[test]
fn a_truncated_log_still_verifies_as_its_older_prefix() {
    // A rollback serves a valid prefix (draft-atwood-jmap-did-00
    // §Resolving `did:webvh`: "A rollback is detected only against a
    // newer `versionId` the resolver has already seen"), so the latest
    // versionId is what a caller compares.
    let (did, log) = basic_update_ts();
    let first = log.split(|&b| b == b'\n').next().unwrap();
    let full = verify_webvh_log(&did, &log, None, now()).unwrap();
    let prefix = verify_webvh_log(&did, first, None, now()).unwrap();
    assert_eq!(prefix.invalid_entry(), None);
    assert_eq!(prefix.latest().version_number, 1);
    assert_eq!(full.latest().version_number, 2);
    assert_ne!(prefix.latest().version_id, full.latest().version_id);
}

#[test]
fn version_time_tolerance_is_five_minutes() {
    // basic-create/ts has `"versionTime":"2000-01-01T00:00:00Z"`;
    // "Resolvers SHOULD use a tolerance of no more than 5 minutes."
    let log = read(&fixtures().join("basic-create/ts/did.jsonl"));
    let did = created_did(&log);
    let created = UNIX_EPOCH + Duration::from_secs(946_684_800);
    let early = created - Duration::from_secs(5 * 60 + 1);
    let ok = created - Duration::from_secs(5 * 60);
    assert_eq!(
        verify_webvh_log(&did, &log, None, early).err(),
        Some(WebvhError::InvalidVersionTime)
    );
    assert!(verify_webvh_log(&did, &log, None, ok).is_ok());
}

