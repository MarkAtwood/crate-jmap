//! Tests for the pure did:key, did:web and did:plc resolution helpers.
//!
//! Oracles, none produced by this crate:
//!
//! - did:key: the did:key Method v0.9 (W3C CCG,
//!   <https://w3c-ccg.github.io/did-key-spec/>) text and Create example,
//!   and the test vectors that spec repository published in
//!   `test-vectors/*.json` until commit 96136d8. The expected key bytes
//!   were derived from each vector's `seed`, `publicKeyBase58` or
//!   `publicKeyJwk` with Python's `cryptography` and `base64` modules.
//! - did:web: the did:web Method Specification examples
//!   (<https://w3c-ccg.github.io/did-method-web/>).
//! - did:plc: `tests/fixtures/plc/*.audit.json` are audit logs fetched
//!   from `https://plc.directory/<did>/log/audit` on 2026-10-20, and
//!   `*.data.json` the directory's `/<did>/data` state and
//!   `*.document.json` its `/<did>` DID document for the same DIDs.
//!   Each entry's `cid` was computed by the directory, so matching it
//!   checks the DAG-CBOR encoding. `synthetic.json` was generated by
//!   the did:plc reference implementation (`synthetic.js`). Expected
//!   verdicts quote the did:plc Method Specification v0.3.0
//!   (<https://web.plc.directory/spec/v0.1/did-plc>).

use jmap_did_types::{
    verify_plc_audit_log, Did, DidKey, DidKeyError, KeyType, PlcError, PlcStatus,
};
use serde_json::{json, Value};

fn did(s: &str) -> Did {
    s.parse().unwrap()
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

