#[test]
fn plc_recovery_within_window_by_higher_key_nullifies() {
    // §Key Rotation & Account Recovery: a higher-authority key "must sign
    // a new operation that points to the CID of the last 'valid'
    // operation - ie the fork point", accepted when "it is submitted
    // within 72hrs of the to-be-invalidated operation" and "the key used
    // for the signature has a lower index in the rotationKeys array than
    // the key that signed the to-be-invalidated operation". Entry 1
    // (signed by rotationKeys[1]) is nullified by entry 2 (signed by
    // rotationKeys[0], 71h59m59s later), which sets rotationKeys to the
    // recovery key alone and keeps the genesis handle.
    let synthetic = fixture("synthetic.json");
    let state =
        active_state(verify(synthetic["did"].as_str().unwrap(), &synthetic["recovery"]).unwrap());
    assert_eq!(
        state["rotationKeys"],
        json!([synthetic["keys"]["recovery"]])
    );
    assert_eq!(state["alsoKnownAs"], json!(["at://alice.test"]));
}

#[test]
fn plc_recovery_after_window_is_rejected() {
    // "it is submitted within 72hrs of the to-be-invalidated operation":
    // entry 2 comes 72 hours and 1 ms after entry 1.
    let synthetic = fixture("synthetic.json");
    assert!(matches!(
        verify(
            synthetic["did"].as_str().unwrap(),
            &synthetic["lateRecovery"]
        ),
        Err(PlcError::LateRecovery { index: 2 })
    ));
}

